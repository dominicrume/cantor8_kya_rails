"""A dated index of every public artefact, built from live sources.

Written for a Tech Nation Global Talent endorsement, but it is the document any
assessment needs: what exists, when it appeared, where to verify it, and what
each item actually demonstrates.

    python3 tools/evidence_pack.py > docs/evidence/index.md

GENERATED, NOT WRITTEN, and that is the point. An evidence pack typed by hand
goes stale the week after it is typed, and the one number nobody rechecks is
the one an assessor checks first. Every date and count below comes from the
GitHub API, the PyPI API or the Canton forum's public JSON at the moment this
runs. Anything unreachable is printed as unreachable rather than remembered.

Two things it deliberately does NOT do.

It does not score the application. Mapping an artefact to a criterion is a
judgement, and the judgements here are marked as such so a reader can disagree
with them without disagreeing with the facts.

It does not inflate. 189 downloads a month is 189 downloads a month. The rest
of this repository exists because of what happens when a number gets rounded in
its author's favour.
"""
