def gh(path):
    p = subprocess.run(["gh", "api", path],  # nosec B603 B607 - literal argv
                       capture_output=True, text=True, timeout=60)
    if p.returncode != 0:
        return None
    try:
        return json.loads(p.stdout)
    except ValueError:
        return None


def web(url, tries=3):
    """Read a JSON endpoint, retrying a rate limit rather than blanking a number.

    pypistats returns 429 under load. The first version treated that the same
    as unreachable and printed "download stats unreachable" into the evidence
    pack, which is a blank where a real figure exists. A transient failure that
    silently removes evidence is worse than one that stops.
    """
    last = None
    for attempt in range(tries):
        try:
            with urllib.request.urlopen(url, timeout=30) as r:  # nosec B310
                return json.loads(r.read())
        except Exception as e:               # noqa: BLE001 - unreachable is an answer
            last = e
            if attempt < tries - 1:
                time.sleep(2 * (attempt + 1))
    print("<!-- %s: %s -->" % (url, str(last)[:70]))
    return None


CACHE = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                     "..", "docs", "evidence", "downloads.json")


def downloads(name):
    """Download figures, cached with the date they were true.

    pypistats rate-limits hard, and a 429 was blanking a real number out of the
    evidence pack. A figure that vanishes because a third party was busy is a
    worse record than a figure carrying the date it was measured, which is what
    an evidence pack should contain anyway.
    """
    try:
        with open(CACHE) as f:
            cache = json.load(f)
    except (OSError, ValueError):
        cache = {}
    live = web("https://pypistats.org/api/packages/%s/recent" % name, tries=2)
    if live:
        cache[name] = {"month": live["data"]["last_month"],
                       "week": live["data"]["last_week"],
                       "measured": datetime.now(timezone.utc).strftime("%Y-%m-%d")}
        os.makedirs(os.path.dirname(CACHE), exist_ok=True)
        with open(CACHE, "w") as f:
            json.dump(cache, f, indent=2, sort_keys=True)
    got = cache.get(name)
    if not got:
        return "download figures not yet measured"
    return ("%s downloads in the last month, %s in the last week, measured %s"
            % (got["month"], got["week"], got["measured"]))


def row(date, what, url, shows, crit):
    return "| %s | %s | %s | %s | %s |" % (date, what, url, shows, crit)


